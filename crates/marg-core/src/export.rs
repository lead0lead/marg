//! Markdown export of the annotations (§2.11).

use crate::annotlist::Entry;
use crate::config::Config;

/// The placeholders of the citation template.
const PLACEHOLDERS: [&str; 4] = ["author", "year", "page", "title"];

/// What the export is made from.
pub struct Export<'a> {
    /// The PDF's file name, for the first line.
    pub file_name: &'a str,
    /// The title from the metadata; the file name when `None`.
    pub title: Option<&'a str>,
    /// `YYYY-MM-DD`.
    pub date: &'a str,
    /// Page labels, if the PDF has them.
    pub labels: Option<&'a [String]>,
    /// Category names, in order.
    pub categories: &'a [&'a str],
    /// `:export md cite`: quotes end with this citation instead of the
    /// page number.
    pub cite: Option<Cite<'a>>,
}

/// What a quote's citation is made from.
pub struct Cite<'a> {
    /// `export.citation`.
    pub template: &'a str,
    pub author: &'a str,
    /// Empty: "n.d.".
    pub year: &'a str,
}

/// The Markdown text for `entries` (in reading order, as the annotation
/// list builds them): one section per category in category order, then
/// "Uncategorised"; empty sections are left out.
pub fn markdown(x: &Export, entries: &[Entry]) -> String {
    let mut out = format!(
        "<!-- Generated by marg from {} on {}. Re-exporting overwrites this file. -->\n# {}\n",
        x.file_name,
        x.date,
        one_line(x.title.unwrap_or(x.file_name)),
    );
    let sections = (0..x.categories.len())
        .map(Some)
        .chain(std::iter::once(None));
    for cat in sections {
        let mut items = entries.iter().filter(|e| e.category == cat).peekable();
        if items.peek().is_none() {
            continue;
        }
        let name = cat.map_or("Uncategorised", |c| x.categories[c]);
        out.push_str(&format!("\n## {}\n", one_line(name)));
        for e in items {
            let page = x
                .labels
                .and_then(|l| l.get(e.page))
                .cloned()
                .unwrap_or_else(|| (e.page + 1).to_string());
            out.push('\n');
            if e.marked {
                let source = match &x.cite {
                    Some(c) => citation(c, &page, x.title.unwrap_or(x.file_name)),
                    None => format!("p. {page}"),
                };
                out.push_str(&format!("> {}\n> — {source}\n", one_line(&e.text)));
            } else {
                out.push_str(&format!("**{}** — p. {page}\n", e.text));
            }
            let comment = e.comment.trim();
            if !comment.is_empty() {
                out.push('\n');
                out.push_str(comment);
                out.push('\n');
            }
        }
    }
    out
}

/// The template with its placeholders filled in; unknown ones are kept as
/// written.
fn citation(c: &Cite, page: &str, title: &str) -> String {
    let year = c.year.trim();
    let values = [
        one_line(c.author),
        if year.is_empty() {
            "n.d.".into()
        } else {
            one_line(year)
        },
        page.to_string(),
        one_line(title),
    ];
    let mut out = one_line(c.template);
    for (name, value) in PLACEHOLDERS.iter().zip(values) {
        out = out.replace(&format!("{{{name}}}"), &value);
    }
    out
}

/// The year of a PDF date (`D:20240315…`, or anything starting with four
/// digits), for prefilling the year prompt.
pub fn year(pdf_date: &str) -> Option<String> {
    let d = pdf_date.trim();
    let d = d.strip_prefix("D:").unwrap_or(d);
    let y: String = d.chars().take(4).collect();
    (y.len() == 4 && y.chars().all(|c| c.is_ascii_digit())).then_some(y)
}

/// Config problems, for the status bar: `{names}` in the citation template
/// that are not placeholders.
pub fn check(config: &Config) -> Vec<String> {
    let mut out = Vec::new();
    let mut rest = config.export.citation.as_str();
    while let Some((_, after)) = rest.split_once('{') {
        let Some((name, next)) = after.split_once('}') else {
            break;
        };
        if !PLACEHOLDERS.contains(&name) {
            out.push(format!(
                "export.citation: unknown placeholder {{{name}}} (known: {})",
                PLACEHOLDERS.map(|p| format!("{{{p}}}")).join(", ")
            ));
        }
        rest = next;
    }
    out
}

/// `text` with line breaks and runs of whitespace as single spaces.
fn one_line(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

/// The UTC date of `secs` since the Unix epoch, as `YYYY-MM-DD`.
pub fn date(secs: u64) -> String {
    // Howard Hinnant's civil_from_days.
    let z = (secs / 86_400) as i64 + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let day = doy - (153 * mp + 2) / 5 + 1;
    let month = if mp < 10 { mp + 3 } else { mp - 9 };
    let year = yoe + era * 400 + i64::from(month <= 2);
    format!("{year:04}-{month:02}-{day:02}")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn entry(page: usize, category: Option<usize>, text: &str, comment: &str) -> Entry {
        Entry {
            page,
            xref: 0,
            category,
            color: None,
            marked: !text.starts_with('['),
            text: text.into(),
            comment: comment.into(),
        }
    }

    #[test]
    fn sections_in_category_order_then_uncategorised() {
        let labels: Vec<String> = ["i", "ii", "1"].map(String::from).into();
        let x = Export {
            file_name: "paper.pdf",
            title: Some("A Paper"),
            date: "2026-10-27",
            labels: Some(&labels),
            categories: &["Key point", "Question", "Definition"],
            cite: None,
        };
        let entries = [
            entry(0, Some(1), "[Box]", "Comment on the box."),
            entry(1, Some(0), "The highlighted\ntext.", "The comment."),
            entry(2, None, "Foreign", ""),
            entry(2, Some(0), "Next highlight", ""),
            entry(2, Some(1), "[Note]", "  a note\nwith two lines \n"),
        ];
        assert_eq!(
            markdown(&x, &entries),
            "<!-- Generated by marg from paper.pdf on 2026-10-27. \
             Re-exporting overwrites this file. -->\n\
             # A Paper\n\
             \n## Key point\n\
             \n> The highlighted text.\n> — p. ii\n\
             \nThe comment.\n\
             \n> Next highlight\n> — p. 1\n\
             \n## Question\n\
             \n**[Box]** — p. i\n\
             \nComment on the box.\n\
             \n**[Note]** — p. 1\n\
             \na note\nwith two lines\n\
             \n## Uncategorised\n\
             \n> Foreign\n> — p. 1\n"
        );
    }

    #[test]
    fn file_name_as_title_and_page_numbers_without_labels() {
        let x = Export {
            file_name: "slides.pdf",
            title: None,
            date: "2026-01-01",
            labels: None,
            categories: &["Key point"],
            cite: None,
        };
        let md = markdown(&x, &[entry(4, Some(0), "five", "")]);
        assert!(md.contains("\n# slides.pdf\n"));
        assert!(md.ends_with("> five\n> — p. 5\n"));
        assert!(!markdown(&x, &[]).contains("##"));
    }

    #[test]
    fn quotes_end_with_the_citation_and_boxes_keep_the_page() {
        let labels: Vec<String> = ["12"].map(String::from).into();
        let x = Export {
            file_name: "paper.pdf",
            title: Some("A\nPaper"),
            date: "2026-01-01",
            labels: Some(&labels),
            categories: &["Key point"],
            cite: Some(Cite {
                template: "({author}, {year}, p. {page}) {title} {x}",
                author: " Smith &\nLee ",
                year: "2024",
            }),
        };
        let md = markdown(
            &x,
            &[
                entry(0, Some(0), "quote", ""),
                entry(0, Some(0), "[Box]", ""),
            ],
        );
        assert!(md.contains("\n> quote\n> — (Smith & Lee, 2024, p. 12) A Paper {x}\n"));
        assert!(md.ends_with("\n**[Box]** — p. 12\n"));
    }

    #[test]
    fn empty_year_is_no_date() {
        let c = Cite {
            template: "({author}, {year})",
            author: "Smith",
            year: " ",
        };
        assert_eq!(citation(&c, "1", "t"), "(Smith, n.d.)");
    }

    #[test]
    fn year_of_pdf_dates() {
        assert_eq!(year("D:20240315120000+01'00'").as_deref(), Some("2024"));
        assert_eq!(year("2019-05-01").as_deref(), Some("2019"));
        assert_eq!(year("D:24"), None);
        assert_eq!(year(""), None);
        assert_eq!(year("Tuesday"), None);
    }

    #[test]
    fn unknown_placeholders_are_problems() {
        assert!(check(&Config::default()).is_empty());
        let mut c = Config::default();
        c.export.citation = "{author} {yr} {page".into();
        assert_eq!(
            check(&c),
            [
                "export.citation: unknown placeholder {yr} (known: {author}, {year}, {page}, {title})"
            ]
        );
    }

    #[test]
    fn dates() {
        assert_eq!(date(0), "1970-01-01");
        assert_eq!(date(951_782_400), "2000-02-29");
        assert_eq!(date(1_793_232_000), "2026-10-29");
    }
}
